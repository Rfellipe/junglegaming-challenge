#!/bin/sh
# Full release gate; integration tests create and remove isolated databases/queues.
set -eu
if [ -n "$(gofmt -l cmd internal integration)" ]; then
  echo 'Go sources require gofmt' >&2
  exit 1
fi
go test ./...
go test -race ./...
go vet ./...
go vet -tags=integration ./...
docker compose up --build --detach --wait
go test -tags=integration -race -count=1 -timeout=5m ./...
